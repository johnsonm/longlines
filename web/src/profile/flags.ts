/** The flag-icons code for a cty.dat entity name, or null when it has none or is unknown. */
export function flagCode(country: string | null | undefined): string | null {
  if (!country) return null;
  return FLAGS[country] ?? null;
}

/** The URL of the flag for a cty.dat entity name, or null when it has none or is unknown. */
export function flagUrl(country: string | null | undefined): string | null {
  const code = flagCode(country);
  return code ? FLAG_URLS[`../../node_modules/flag-icons/flags/4x3/${code}.svg`] ?? null : null;
}

/** Every entity the table knows; flags.test.ts compares it with the cty.dat fixture. */
export function knownEntities(): string[] {
  return Object.keys(FLAGS);
}
